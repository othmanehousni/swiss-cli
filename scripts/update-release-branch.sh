#!/usr/bin/env bash
# Commits the built package to the `release` branch, which is what
#   npm install -g github:othmanehousni/swiss-cli#release
# installs. Run by .github/workflows/release.yml after every push to main; dist/ must already
# be built (npm ci does that).
#
# Why a separate branch: npm "prepares" a package installed from git (installs its
# devDependencies and builds it) whenever package.json has a build, prepare, prepack,
# preinstall, install or postinstall script, and with -g that step installs into the global
# folder instead of the clone and fails. The release branch holds dist/ already built and a
# package.json without scripts, so npm has nothing to prepare.
#
# Settings (environment): RELEASE_REMOTE (default origin), RELEASE_BRANCH (default release).
set -euo pipefail

remote="${RELEASE_REMOTE:-origin}"
branch="${RELEASE_BRANCH:-release}"

repo_root="$(git rev-parse --show-toplevel)"
git_dir="$(git rev-parse --absolute-git-dir)"
source_sha="$(git rev-parse HEAD)"
cd "$repo_root"

if [[ ! -f dist/swiss.js || ! -f dist/cli.js ]]; then
  echo "dist/ is not built: run npm ci (or npm run build) first" >&2
  exit 1
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# 1. Exactly the files npm would publish: package.json, README.md, dist/, supabase/.
npm pack --ignore-scripts --loglevel=warn --pack-destination "$work" >/dev/null
mkdir "$work/pkg"
tar -xzf "$work"/*.tgz -C "$work/pkg"
pkg="$work/pkg/package"

# 2. Nothing left for npm to prepare: no scripts, and no devDependencies to install.
node -e '
  const fs = require("node:fs");
  const file = process.argv[1];
  const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
  delete manifest.scripts;
  delete manifest.devDependencies;
  fs.writeFileSync(file, `${JSON.stringify(manifest, null, 2)}\n`);
' "$pkg/package.json"

# 3. The current tip of the release branch, if there is one, becomes the parent.
parent=""
set +e
git ls-remote --exit-code --heads "$remote" "refs/heads/$branch" >/dev/null
found=$?
set -e
case "$found" in
  0)
    git fetch --quiet --depth=1 "$remote" "refs/heads/$branch"
    parent="$(git rev-parse FETCH_HEAD)"
    ;;
  2) echo "No $branch branch on $remote yet: starting it." ;;
  *)
    echo "Could not reach $remote" >&2
    exit "$found"
    ;;
esac

# 4. Snapshot the files into a commit without checking anything out (separate index file).
export GIT_INDEX_FILE="$work/index"
git --git-dir="$git_dir" --work-tree="$pkg" add --all --force -- "$pkg"
tree="$(git --git-dir="$git_dir" write-tree)"

if [[ -n "$parent" && "$(git rev-parse "$parent^{tree}")" == "$tree" ]]; then
  echo "$branch is already up to date with $source_sha."
  exit 0
fi

message="Build of ${source_sha}

Generated by scripts/update-release-branch.sh from main; do not commit here by hand."
commit="$(git commit-tree "$tree" ${parent:+-p "$parent"} -m "$message")"

git push --quiet "$remote" "$commit:refs/heads/$branch"
echo "Pushed $commit to $branch (build of $source_sha)."
